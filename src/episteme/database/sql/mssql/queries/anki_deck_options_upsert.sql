-- $rows is a list of AnkiDeckOptions rows, sent as JSON; one statement stores them all.
MERGE [{schema}].anki_deck_options WITH (HOLDLOCK) AS target
USING (
    SELECT * FROM OPENJSON($rows) WITH (
        options_id BIGINT '$.options_id',
        name NVARCHAR(450) '$.name',
        modified_at DATETIME2(6) '$.modified_at',
        new_per_day INT '$.new_per_day',
        reviews_per_day INT '$.reviews_per_day',
        new_per_day_minimum INT '$.new_per_day_minimum',
        learn_steps_minutes NVARCHAR(MAX) '$.learn_steps_minutes' AS JSON,
        relearn_steps_minutes NVARCHAR(MAX) '$.relearn_steps_minutes' AS JSON,
        graduating_interval_good_days INT '$.graduating_interval_good_days',
        graduating_interval_easy_days INT '$.graduating_interval_easy_days',
        initial_ease_percent INT '$.initial_ease_percent',
        easy_multiplier FLOAT '$.easy_multiplier',
        hard_multiplier FLOAT '$.hard_multiplier',
        lapse_multiplier FLOAT '$.lapse_multiplier',
        interval_multiplier FLOAT '$.interval_multiplier',
        maximum_interval_days INT '$.maximum_interval_days',
        minimum_lapse_interval_days INT '$.minimum_lapse_interval_days',
        leech_threshold INT '$.leech_threshold',
        leech_action NVARCHAR(100) '$.leech_action',
        bury_new BIT '$.bury_new',
        bury_reviews BIT '$.bury_reviews',
        bury_interday_learning BIT '$.bury_interday_learning',
        new_card_insert_order NVARCHAR(100) '$.new_card_insert_order',
        new_card_gather_priority NVARCHAR(100) '$.new_card_gather_priority',
        new_card_sort_order NVARCHAR(100) '$.new_card_sort_order',
        review_order NVARCHAR(100) '$.review_order',
        new_mix NVARCHAR(100) '$.new_mix',
        interday_learning_mix NVARCHAR(100) '$.interday_learning_mix',
        desired_retention FLOAT '$.desired_retention',
        historical_retention FLOAT '$.historical_retention',
        fsrs_params NVARCHAR(MAX) '$.fsrs_params' AS JSON,
        fsrs_params_version INT '$.fsrs_params_version',
        easy_days_percentages NVARCHAR(MAX) '$.easy_days_percentages' AS JSON,
        ignore_revlogs_before NVARCHAR(100) '$.ignore_revlogs_before'
    )
) AS source ON target.options_id = source.options_id
WHEN MATCHED THEN UPDATE SET
    name = source.name,
    modified_at = source.modified_at,
    new_per_day = source.new_per_day,
    reviews_per_day = source.reviews_per_day,
    new_per_day_minimum = source.new_per_day_minimum,
    learn_steps_minutes = source.learn_steps_minutes,
    relearn_steps_minutes = source.relearn_steps_minutes,
    graduating_interval_good_days = source.graduating_interval_good_days,
    graduating_interval_easy_days = source.graduating_interval_easy_days,
    initial_ease_percent = source.initial_ease_percent,
    easy_multiplier = source.easy_multiplier,
    hard_multiplier = source.hard_multiplier,
    lapse_multiplier = source.lapse_multiplier,
    interval_multiplier = source.interval_multiplier,
    maximum_interval_days = source.maximum_interval_days,
    minimum_lapse_interval_days = source.minimum_lapse_interval_days,
    leech_threshold = source.leech_threshold,
    leech_action = source.leech_action,
    bury_new = source.bury_new,
    bury_reviews = source.bury_reviews,
    bury_interday_learning = source.bury_interday_learning,
    new_card_insert_order = source.new_card_insert_order,
    new_card_gather_priority = source.new_card_gather_priority,
    new_card_sort_order = source.new_card_sort_order,
    review_order = source.review_order,
    new_mix = source.new_mix,
    interday_learning_mix = source.interday_learning_mix,
    desired_retention = source.desired_retention,
    historical_retention = source.historical_retention,
    fsrs_params = source.fsrs_params,
    fsrs_params_version = source.fsrs_params_version,
    easy_days_percentages = source.easy_days_percentages,
    ignore_revlogs_before = source.ignore_revlogs_before
WHEN NOT MATCHED THEN INSERT (options_id, name, modified_at, new_per_day, reviews_per_day, new_per_day_minimum, learn_steps_minutes, relearn_steps_minutes, graduating_interval_good_days, graduating_interval_easy_days, initial_ease_percent, easy_multiplier, hard_multiplier, lapse_multiplier, interval_multiplier, maximum_interval_days, minimum_lapse_interval_days, leech_threshold, leech_action, bury_new, bury_reviews, bury_interday_learning, new_card_insert_order, new_card_gather_priority, new_card_sort_order, review_order, new_mix, interday_learning_mix, desired_retention, historical_retention, fsrs_params, fsrs_params_version, easy_days_percentages, ignore_revlogs_before)
VALUES (source.options_id, source.name, source.modified_at, source.new_per_day, source.reviews_per_day, source.new_per_day_minimum, source.learn_steps_minutes, source.relearn_steps_minutes, source.graduating_interval_good_days, source.graduating_interval_easy_days, source.initial_ease_percent, source.easy_multiplier, source.hard_multiplier, source.lapse_multiplier, source.interval_multiplier, source.maximum_interval_days, source.minimum_lapse_interval_days, source.leech_threshold, source.leech_action, source.bury_new, source.bury_reviews, source.bury_interday_learning, source.new_card_insert_order, source.new_card_gather_priority, source.new_card_sort_order, source.review_order, source.new_mix, source.interday_learning_mix, source.desired_retention, source.historical_retention, source.fsrs_params, source.fsrs_params_version, source.easy_days_percentages, source.ignore_revlogs_before);
