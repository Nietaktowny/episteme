-- $rows is a list of options presets (see AnkiDeckOptions); one statement stores them all.
INSERT INTO anki_deck_options
SELECT
    r.options_id::BIGINT, r.name::TEXT, r.modified_at::TIMESTAMP, r.new_per_day::INTEGER, r.reviews_per_day::INTEGER,
    r.new_per_day_minimum::INTEGER, r.learn_steps_minutes::DOUBLE[], r.relearn_steps_minutes::DOUBLE[],
    r.graduating_interval_good_days::INTEGER, r.graduating_interval_easy_days::INTEGER, r.initial_ease_percent::INTEGER,
    r.easy_multiplier::DOUBLE, r.hard_multiplier::DOUBLE, r.lapse_multiplier::DOUBLE, r.interval_multiplier::DOUBLE,
    r.maximum_interval_days::INTEGER, r.minimum_lapse_interval_days::INTEGER, r.leech_threshold::INTEGER,
    r.leech_action::TEXT, r.bury_new::BOOLEAN, r.bury_reviews::BOOLEAN, r.bury_interday_learning::BOOLEAN,
    r.new_card_insert_order::TEXT, r.new_card_gather_priority::TEXT, r.new_card_sort_order::TEXT, r.review_order::TEXT,
    r.new_mix::TEXT, r.interday_learning_mix::TEXT, r.desired_retention::DOUBLE, r.historical_retention::DOUBLE,
    r.fsrs_params::DOUBLE[], r.fsrs_params_version::INTEGER, r.easy_days_percentages::DOUBLE[], r.ignore_revlogs_before::TEXT
FROM unnest($rows) AS t(r)
ON CONFLICT (options_id) DO UPDATE SET
    name = excluded.name,
    modified_at = excluded.modified_at,
    new_per_day = excluded.new_per_day,
    reviews_per_day = excluded.reviews_per_day,
    new_per_day_minimum = excluded.new_per_day_minimum,
    learn_steps_minutes = excluded.learn_steps_minutes,
    relearn_steps_minutes = excluded.relearn_steps_minutes,
    graduating_interval_good_days = excluded.graduating_interval_good_days,
    graduating_interval_easy_days = excluded.graduating_interval_easy_days,
    initial_ease_percent = excluded.initial_ease_percent,
    easy_multiplier = excluded.easy_multiplier,
    hard_multiplier = excluded.hard_multiplier,
    lapse_multiplier = excluded.lapse_multiplier,
    interval_multiplier = excluded.interval_multiplier,
    maximum_interval_days = excluded.maximum_interval_days,
    minimum_lapse_interval_days = excluded.minimum_lapse_interval_days,
    leech_threshold = excluded.leech_threshold,
    leech_action = excluded.leech_action,
    bury_new = excluded.bury_new,
    bury_reviews = excluded.bury_reviews,
    bury_interday_learning = excluded.bury_interday_learning,
    new_card_insert_order = excluded.new_card_insert_order,
    new_card_gather_priority = excluded.new_card_gather_priority,
    new_card_sort_order = excluded.new_card_sort_order,
    review_order = excluded.review_order,
    new_mix = excluded.new_mix,
    interday_learning_mix = excluded.interday_learning_mix,
    desired_retention = excluded.desired_retention,
    historical_retention = excluded.historical_retention,
    fsrs_params = excluded.fsrs_params,
